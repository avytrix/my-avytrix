document.addEventListener("DOMContentLoaded", function () {
  // Mobile menu toggle
  const menuToggle = document.querySelector(".menu-toggle");
  const mobileMenu = document.getElementById("mobile-menu");
  if (menuToggle && mobileMenu) {
    menuToggle.addEventListener("click", () => {
      const isActive = mobileMenu.classList.toggle("hidden");
      menuToggle.textContent = isActive ? "☰" : "×";
    });
  }

  // Mobile submenu toggle
  document
    .querySelectorAll("#mobile-menu .menu-item-has-children > a")
    .forEach((itemLink) => {
      itemLink.addEventListener("click", function (e) {
        e.preventDefault();
        const subMenu = itemLink.nextElementSibling;
        if (subMenu && subMenu.classList.contains("submenu")) {
          subMenu.classList.toggle("active");
          const icon = itemLink.querySelector("span");
          if (icon)
            icon.textContent = subMenu.classList.contains("active") ? "−" : "+";
        }
      });
    });

  // Contact form functionality
  const contactPage = document.getElementById("premium-contact-page");
  if (contactPage) {
    const wrapper = contactPage.querySelector(".custom-select-wrapper");
    if (wrapper) {
      const trigger = wrapper.querySelector(".custom-select-trigger");
      const triggerText = trigger.querySelector("span");
      const options = wrapper.querySelectorAll(".custom-option");
      const hiddenInput = wrapper.querySelector("#service_interest_input");
      const customOptions = wrapper.querySelector(".custom-options");

      console.log("Custom select initialized");
      console.log("Hidden input:", hiddenInput);

      // Set default value for the service interest field
      if (hiddenInput) {
        hiddenInput.value = "Web Development";
        console.log("Default service interest set to:", hiddenInput.value);
      }

      trigger.addEventListener("click", () => {
        console.log("Custom select clicked");
        customOptions.classList.remove("hidden");
      });
      options.forEach((option) => {
        option.addEventListener("click", () => {
          const selectedValue = option.getAttribute("data-value");
          console.log("Option selected:", selectedValue);
          triggerText.textContent = selectedValue;
          if (hiddenInput) {
            hiddenInput.value = selectedValue;
            console.log("Hidden input value set to:", hiddenInput.value);
          }
          wrapper.classList.remove("open");
          customOptions.classList.add("hidden");
        });
      });
      window.addEventListener("click", (e) => {
        if (!wrapper.contains(e.target)) wrapper.classList.remove("open");
      });
    }

    // Form submission handling
    const form = document.getElementById("contact-form");
    const submitButton = form.querySelector(".btn-submit");
    const successModal = document.getElementById("success-modal");
    const closeModalBtn = document.getElementById("close-modal-btn");

    const nameInput = form.querySelector("#name");
    const emailInput = form.querySelector("#email");
    const companyInput = form.querySelector("#company");
    const messageInput = form.querySelector("#message");
    const honeypotInput = form.querySelector("#website_url");
    const timestampInput = form.querySelector("#form_timestamp");

    // Set form load time for bot detection
    const formLoadTime = Date.now();
    if (timestampInput) {
      timestampInput.value = formLoadTime;
    }

    // Rate limiting
    const RATE_LIMIT_KEY = "viliha_form_submissions";
    const RATE_LIMIT_MAX = 3;
    const RATE_LIMIT_WINDOW = 3600000;

    const checkRateLimit = () => {
      const submissions = JSON.parse(
        localStorage.getItem(RATE_LIMIT_KEY) || "[]"
      );
      const now = Date.now();

      const recentSubmissions = submissions.filter(
        (time) => now - time < RATE_LIMIT_WINDOW
      );
      localStorage.setItem(RATE_LIMIT_KEY, JSON.stringify(recentSubmissions));
      return recentSubmissions.length < RATE_LIMIT_MAX;
    };

    const recordSubmission = () => {
      const submissions = JSON.parse(
        localStorage.getItem(RATE_LIMIT_KEY) || "[]"
      );
      submissions.push(Date.now());
      localStorage.setItem(RATE_LIMIT_KEY, JSON.stringify(submissions));
    };

    // Input sanitization
    const sanitizeInput = (str) => {
      if (!str) return "";
      return str
        .replace(/[<>]/g, "")
        .replace(/javascript:/gi, "")
        .replace(/on\w+=/gi, "")
        .trim();
    };

    // Email validation
    const validateEmail = (email) => {
      const re =
        /^(([^<>()[\]\\.,;:\s@"]+(\.[^<>()[\]\\.,;:\s@"]+)*)|(".+"))@((\[[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\])|(([a-zA-Z\-0-9]+\.)+[a-zA-Z]{2,}))$/;
      return re.test(String(email).toLowerCase());
    };

    // Check for disposable email
    const isDisposableEmail = (email) => {
      const disposableDomains = [
        "tempmail.com",
        "throwaway.email",
        "guerrillamail.com",
        "mailinator.com",
        "temp-mail.org",
        "10minutemail.com",
        "fakeinbox.com",
        "trashmail.com",
        "yopmail.com",
        "getnada.com",
        "mohmal.com",
        "dispostable.com",
        "mailnesia.com",
        "tempr.email",
        "discard.email",
        "throwawaymail.com",
      ];
      const domain = email.split("@")[1]?.toLowerCase();
      return disposableDomains.some((d) => domain?.includes(d));
    };

    // Validate email domain
    const isValidEmailDomain = (email) => {
      const domain = email.split("@")[1]?.toLowerCase();
      if (!domain) return false;

      const domainParts = domain.split(".");
      if (domainParts.length < 2) return false;

      const tld = domainParts[domainParts.length - 1];
      if (tld.length < 2) return false;

      const validTLDs = [
        "com",
        "org",
        "net",
        "edu",
        "gov",
        "mil",
        "int",
        "io",
        "co",
        "ai",
        "app",
        "dev",
        "tech",
        "info",
        "biz",
        "name",
        "pro",
        "mobi",
        "tel",
        "asia",
        "eu",
        "de",
        "uk",
        "fr",
        "it",
        "es",
        "nl",
        "be",
        "at",
        "ch",
        "pl",
        "ru",
        "cn",
        "jp",
        "kr",
        "in",
        "au",
        "nz",
        "ca",
        "us",
        "mx",
        "br",
        "ar",
        "za",
        "ae",
        "sg",
        "hk",
        "tw",
        "th",
        "my",
        "id",
        "ph",
        "vn",
        "pk",
        "bd",
        "ng",
        "eg",
        "tr",
        "il",
        "sa",
        "qa",
        "kw",
        "se",
        "no",
        "dk",
        "fi",
        "ie",
        "pt",
        "gr",
        "cz",
        "hu",
        "ro",
        "bg",
        "hr",
        "sk",
        "si",
        "rs",
        "ua",
        "by",
        "kz",
        "cloud",
        "online",
        "store",
        "shop",
        "site",
        "website",
        "blog",
        "agency",
        "digital",
        "media",
        "design",
        "studio",
        "solutions",
        "services",
        "consulting",
        "group",
        "company",
        "business",
        "marketing",
        "software",
        "systems",
        "network",
        "xyz",
      ];

      if (!validTLDs.includes(tld)) return false;

      const domainName = domainParts.slice(0, -1).join(".");
      if (domainName.length < 2) return false;

      const consonantPattern = /[bcdfghjklmnpqrstvwxyz]{5,}/i;
      if (consonantPattern.test(domainName)) return false;

      const repeatedPattern = /(.)\1{3,}/;
      if (repeatedPattern.test(domainName)) return false;

      const trustedDomains = [
        "gmail.com",
        "yahoo.com",
        "outlook.com",
        "hotmail.com",
        "live.com",
        "icloud.com",
        "me.com",
        "mac.com",
        "aol.com",
        "msn.com",
        "protonmail.com",
        "proton.me",
        "zoho.com",
        "mail.com",
        "gmx.com",
        "gmx.net",
        "yandex.com",
        "fastmail.com",
        "tutanota.com",
        "hey.com",
        "pm.me",
      ];

      if (trustedDomains.includes(domain)) return true;

      return true;
    };

    // Email verification (placeholder for API integration)
    const verifyEmailExists = async (email) => {
      const trustedDomains = [
        "gmail.com",
        "yahoo.com",
        "outlook.com",
        "hotmail.com",
        "live.com",
        "icloud.com",
        "me.com",
        "mac.com",
        "aol.com",
        "msn.com",
        "protonmail.com",
        "proton.me",
        "zoho.com",
        "mail.com",
        "gmx.com",
        "gmx.net",
        "yandex.com",
        "fastmail.com",
        "tutanota.com",
        "hey.com",
        "pm.me",
      ];
      const domain = email.split("@")[1]?.toLowerCase();
      if (trustedDomains.includes(domain)) {
        return { valid: true, reason: "trusted_domain" };
      }

      try {
        // Email verification API - get API key from Hugo config
        const apiKey =
          window.VILIHA_CONFIG && window.VILIHA_CONFIG.abstractApiKey;

        if (!apiKey) {
          console.log("Email verification API not configured");
          return { valid: true, reason: "api_not_configured" };
        }

        const response = await fetch(
          `${
            window.VILIHA_CONFIG.abstractApiUrl ||
            "https://emailreputation.abstractapi.com/v1/"
          }?api_key=${apiKey}&email=${encodeURIComponent(email)}`
        );

        if (!response.ok) {
          console.log("Email verification API error");
          return { valid: true, reason: "api_error" };
        }

        const data = await response.json();

        // Check if email is deliverable based on the expected API response format
        if (
          data.email_deliverability &&
          data.email_deliverability.status === "undeliverable"
        ) {
          return {
            valid: false,
            reason: "Email address does not exist or cannot receive emails.",
          };
        }

        // Check if email format is valid
        if (
          data.email_deliverability &&
          data.email_deliverability.is_format_valid === false
        ) {
          return { valid: false, reason: "Invalid email format." };
        }

        // Check if SMTP is valid
        if (
          data.email_deliverability &&
          data.email_deliverability.is_smtp_valid === false
        ) {
          return {
            valid: false,
            reason: "Email address does not exist or cannot receive emails.",
          };
        }

        // Check if MX records are valid
        if (
          data.email_deliverability &&
          data.email_deliverability.is_mx_valid === false
        ) {
          return {
            valid: false,
            reason: "Email domain does not have valid mail servers.",
          };
        }

        return { valid: true, reason: "verified" };
      } catch (error) {
        console.log("Email verification failed:", error);
        return { valid: true, reason: "verification_failed" };
      }
    };

    const toggleError = (input, show) => {
      const formGroup = input.parentElement;
      formGroup.classList.toggle("error", show);
    };

    // Form submission
    form.addEventListener("submit", async function (e) {
      e.preventDefault();
      console.log("Form submission started");

      // Honeypot check
      if (honeypotInput && honeypotInput.value !== "") {
        console.log("Bot detected via honeypot");
        showSuccessModal();
        return;
      }

      // Time-based bot detection
      const timeTaken = Date.now() - formLoadTime;
      console.log("Time taken:", timeTaken);
      if (timeTaken < 3000) {
        console.log("Bot detected - form submitted too quickly");
        showSuccessModal();
        return;
      }

      // Rate limiting check
      if (!checkRateLimit()) {
        alert("Too many submissions. Please try again later.");
        return;
      }

      // reCAPTCHA check
      if (window.grecaptcha) {
        const recaptchaResponse = grecaptcha.getResponse();
        if (!recaptchaResponse || recaptchaResponse.length === 0) {
          alert("Please complete the reCAPTCHA verification.");
          return;
        }
      }

      // Form validation
      let isValid = true;

      nameInput.value = sanitizeInput(nameInput.value);
      emailInput.value = sanitizeInput(emailInput.value);
      companyInput.value = sanitizeInput(companyInput.value);
      messageInput.value = sanitizeInput(messageInput.value);

      console.log("Name:", nameInput.value);
      console.log("Email:", emailInput.value);
      console.log("Company:", companyInput.value);
      console.log("Message:", messageInput.value);

      if (nameInput.value.trim() === "" || nameInput.value.length > 100) {
        console.log("Name validation failed");
        toggleError(nameInput, true);
        isValid = false;
      } else {
        toggleError(nameInput, false);
      }

      if (!validateEmail(emailInput.value) || emailInput.value.length > 254) {
        console.log("Email format validation failed");
        toggleError(emailInput, true);
        isValid = false;
      } else if (!isValidEmailDomain(emailInput.value)) {
        console.log("Email domain validation failed");
        toggleError(emailInput, true);
        alert("Please enter a valid email domain.");
        isValid = false;
      } else if (isDisposableEmail(emailInput.value)) {
        console.log("Disposable email detected");
        toggleError(emailInput, true);
        alert("Please use a valid business email address.");
        isValid = false;
      } else {
        toggleError(emailInput, false);
      }

      if (
        messageInput.value.trim() === "" ||
        messageInput.value.length > 5000
      ) {
        console.log("Message validation failed");
        toggleError(messageInput, true);
        isValid = false;
      } else {
        toggleError(messageInput, false);
      }

      console.log("Form validation result:", isValid);
      if (!isValid) return;

      // Show loading state
      submitButton.classList.add("sending");
      submitButton.disabled = true;

      // Verify email
      console.log("Starting email verification for:", emailInput.value);
      const emailVerification = await verifyEmailExists(emailInput.value);
      console.log("Email verification result:", emailVerification);
      if (!emailVerification.valid) {
        console.log(
          "Email verification failed, reason:",
          emailVerification.reason
        );
        toggleError(emailInput, true);
        alert(emailVerification.reason);
        submitButton.classList.remove("sending");
        submitButton.disabled = false;
        return;
      }

      // Record submission
      recordSubmission();

      // Prepare form data
      const formData = new FormData(form);

      // Log form data for debugging
      console.log("Form data prepared:");
      for (let [key, value] of formData.entries()) {
        console.log(key, value);
      }

      // Use jQuery queue for sequential email sending
      const queueObj = $({});

      queueObj
        .queue("sendQueue", function (next) {
          console.log("Sending to customer...");
          sendToCustomer(formData, "template_u5v3z1a");
          next();
        })
        .queue("sendQueue", function (next) {
          console.log("Sending to Viliha...");
          sendToViliha(formData, "template_6uq3gfq");
          next();
        })
        .queue("sendQueue", function (next) {
          console.log("Clearing form...");
          clearForm();
          next();
        });

      queueObj.dequeue("sendQueue");
    });

    // Modal controls
    closeModalBtn.addEventListener("click", () => {
      successModal.classList.add("hidden");
    });

    const showSuccessModal = () => {
      successModal.classList.remove("hidden");
      setTimeout(() => {
        successModal.classList.add("hidden");
      }, 5000);
    };

    // Email sending functions
    function sendToCustomer(formData, templateId) {
      console.log("Sending email to customer with template:", templateId);
      formData.append("template_id", templateId);
      $.ajax("https://api.emailjs.com/api/v1.0/email/send-form", {
        type: "POST",
        data: formData,
        contentType: false,
        processData: false,
      })
        .done(function () {
          console.log("Customer email sent successfully");
          showSuccessModal();
          if (window.grecaptcha) {
            grecaptcha.reset();
          }
          submitButton.classList.remove("sending");
          submitButton.disabled = false;
        })
        .fail(function (error) {
          console.log("Customer email failed:", error);
          alert("Sorry, something went wrong. Your message was not sent.");
        });
    }

    function sendToViliha(formData, templateId) {
      console.log("Sending email to Viliha with template:", templateId);
      formData.set("template_id", templateId);
      formData.append("dateTime", GermanTimeZone());
      $.ajax("https://api.emailjs.com/api/v1.0/email/send-form", {
        type: "POST",
        data: formData,
        contentType: false,
        processData: false,
      });
    }

    function clearForm() {
      nameInput.value = "";
      emailInput.value = "";
      companyInput.value = "";
      messageInput.value = "";
    }

    function GermanTimeZone() {
      const options = {
        timeZone: "Europe/Berlin",
        day: "2-digit",
        month: "long",
        year: "numeric",
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
        hour12: false,
      };

      const dateTimeInGerman = new Intl.DateTimeFormat("de-DE", options).format(
        new Date()
      );
      const formattedDateTime = dateTimeInGerman
        .replace(",", "")
        .replace(/\./g, "")
        .replace(
          /(\d{2}) (\w+) (\d{4}) (\d{2}):(\d{2}):(\d{2})/,
          "$1-$2-$3 $4:$5:$6"
        );
      return formattedDateTime;
    }
  }

  // Tech stack buttons functionality
  const techStackButtons = document.querySelectorAll(".tech-stack-list-button");
  if (techStackButtons) {
    techStackButtons.forEach((button) => {
      button.addEventListener("click", () => {
        document
          .querySelectorAll(".tech-stack-list-button")
          .forEach((btn) => (btn.dataset.active = "false"));
        button.dataset.active = "true";

        document
          .querySelectorAll(".tech-stack-content-item")
          .forEach((item) => item.classList.add("hidden"));
        const target = document.querySelector(button.dataset.target);
        if (target) {
          target.classList.remove("hidden");
          target.classList.add("flex");
        }
      });
    });
  }

  // Interactive list functionality
  const interactiveListContainers = document.querySelectorAll(
    ".interactive-list-button-column"
  );
  if (interactiveListContainers) {
    interactiveListContainers.forEach((container) => {
      const listButtons = container.querySelectorAll(
        ".interactive-list-button"
      );

      listButtons.forEach((button) => {
        button.addEventListener("click", () => {
          const targetId = button.dataset.target;
          const targetContent = document.querySelector(targetId);

          listButtons.forEach((b) => (b.dataset.active = "false"));
          container.parentElement
            .querySelectorAll(".interactive-content-item")
            .forEach((c) => c.classList.add("hidden"));

          button.dataset.active = "true";
          if (targetContent) {
            targetContent.classList.remove("hidden");
          }
        });
      });
    });
  }
});

// Cookie consent functionality
document.addEventListener("DOMContentLoaded", function () {
  const banner = document.getElementById("cookie-consent-banner");
  const acceptBtn = document.getElementById("cookie-consent-accept");
  const declineBtn = document.getElementById("cookie-consent-decline");

  if (!sessionStorage.getItem("cookieConsent")) {
    banner.classList.remove("hidden");
  }

  function acceptCookies() {
    sessionStorage.setItem("cookieConsent", "accepted");
    banner.classList.add("hidden");
  }

  acceptBtn.addEventListener("click", acceptCookies);
  declineBtn.addEventListener("click", acceptCookies);
});
